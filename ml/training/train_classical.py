"""Train the classical (offline) complaint classifier.

TF-IDF (word 1-2 grams) + LogisticRegression over the synthetic dataset
generated by ``ml.datasets.build_datasets``. Runs in seconds, no GPU, no
network. Saves a versioned artifact + metrics JSON to
ml/models/complaint_classifier/.

Usage:  python -m ml.training.train_classical
"""

from __future__ import annotations

import json
import time
from pathlib import Path

from ml.config import config
from ml.preprocessing.lexicons import CATEGORY_LABELS


def train() -> dict:
    import joblib
    from sklearn.feature_extraction.text import TfidfVectorizer
    from sklearn.linear_model import LogisticRegression
    from sklearn.metrics import classification_report, confusion_matrix, f1_score
    from sklearn.pipeline import Pipeline

    data_dir = config.PROJECT_ROOT / "ml" / "datasets" / "data"
    train_path = data_dir / "complaints_train.jsonl"
    eval_path = data_dir / "complaints_eval.jsonl"
    if not train_path.exists():
        raise SystemExit("Dataset missing. Run: python -m ml.datasets.build_datasets")

    def load(path: Path) -> tuple[list[str], list[str]]:
        texts, labels = [], []
        with open(path, encoding="utf-8") as fh:
            for line in fh:
                row = json.loads(line)
                texts.append(row["text"])
                labels.append(row["category"])
        return texts, labels

    X_train, y_train = load(train_path)
    X_eval, y_eval = load(eval_path)

    pipeline = Pipeline([
        ("tfidf", TfidfVectorizer(ngram_range=(1, 2), max_features=20000,
                                  sublinear_tf=True, min_df=2)),
        ("clf", LogisticRegression(max_iter=1000, C=8.0)),
    ])

    start = time.time()
    pipeline.fit(X_train, y_train)
    train_seconds = round(time.time() - start, 2)

    y_pred = pipeline.predict(X_eval)
    macro_f1 = float(f1_score(y_eval, y_pred, average="macro"))
    accuracy = float((pipeline.score(X_eval, y_eval)))
    report = classification_report(y_eval, y_pred, output_dict=True, zero_division=0)
    cm = confusion_matrix(y_eval, y_pred, labels=pipeline.classes_).tolist()

    out_dir = config.PROJECT_ROOT / "ml" / "models" / "complaint_classifier"
    out_dir.mkdir(parents=True, exist_ok=True)
    artifact_path = out_dir / "tfidf_lr.joblib"
    joblib.dump({
        "vectorizer": pipeline.named_steps["tfidf"],
        "clf": pipeline.named_steps["clf"],
        "labels": list(pipeline.classes_),
        "trained_on": "ml/datasets/data/complaints_train.jsonl (synthetic, seed 42)",
    }, artifact_path)

    metrics = {
        "model": "tfidf(1-2gram,20k,sublinear)+logreg(C=8)",
        "artifact": str(artifact_path.name),
        "trained_seconds": train_seconds,
        "n_train": len(X_train),
        "n_eval": len(X_eval),
        "accuracy": round(accuracy, 4),
        "macro_f1": round(macro_f1, 4),
        "labels": list(pipeline.classes_),
        "label_names": {c: CATEGORY_LABELS.get(c, c) for c in pipeline.classes_},
        "per_class": report,
        "confusion_matrix": cm,
        "data_notice": "Metrics are computed on SYNTHETIC demonstration data and do not represent real-world performance.",
    }
    (out_dir / "metrics.json").write_text(json.dumps(metrics, indent=2, ensure_ascii=False))

    print(f"Trained in {train_seconds}s on {len(X_train)} synthetic rows")
    print(f"Eval accuracy: {accuracy:.4f}  macro-F1: {macro_f1:.4f}")
    for cls, vals in sorted(report.items()):
        if cls in pipeline.classes_:
            print(f"  {cls:<24} f1={vals['f1-score']:.3f} support={vals['support']}")
    return metrics


if __name__ == "__main__":
    train()
